均线（MA55/MA233）具备四大核心物理性质：

1. **支撑与压制**：均线的根本任务是维护趋势现状。任何未伴随结构破坏的触线，均应优先判定为支撑或压制有效。
2. **牵引性**：当股价过度偏离MA55/MA233时，均线产生回归引力。首次突破或跌破MA55/MA233，必定伴随回抽确认动作。
